/// Generates all checked-in TypeScript binding artifacts below `output`.
pub fn generate_bindings(output: &Path) -> Result<(), CodegenError> {
    let source = output.join("src");
    let schemas = output.join("schemas");
    fs::create_dir_all(&source)?;
    fs::create_dir_all(&schemas)?;

    write_stable(
        &output.join("package.json"),
        br#"{
  "name": "@jingwei/jdp-bindings",
  "version": "0.1.0",
  "private": true,
  "type": "module",
  "types": "src/generated.ts",
  "scripts": {
    "typecheck": "tsc --noEmit"
  },
  "devDependencies": {
    "typescript": "^5.9.2"
  }
}
"#,
    )?;
    write_stable(
        &output.join("tsconfig.json"),
        br#"{
  "compilerOptions": {
    "strict": true,
    "noEmit": true,
    "target": "ES2022",
    "module": "NodeNext",
    "moduleResolution": "NodeNext",
    "skipLibCheck": true
  },
  "include": ["src/**/*.ts", "test/**/*.ts"]
}
"#,
    )?;
    write_stable(
        &output.join("README.md"),
        b"# Generated JDP TypeScript binding\n\nDo not edit `src/generated.ts` or schemas by hand. Regenerate with:\n\n```text\ncargo run -p jingwei-jdp --bin jingwei-codegen -- bindings/typescript\n```\n",
    )?;
    write_stable(&source.join("generated.ts"), TYPESCRIPT.as_bytes())?;

    let request_schema = serde_json::to_value(schema_for!(JdpRequest<Value>))?;
    let response_schema = serde_json::to_value(schema_for!(JdpResponse<Value>))?;
    let revision_schema = serde_json::to_value(schema_for!(jingwei_jir::RevisionSnapshot))?;
    let lifecycle_schema = serde_json::to_value(schema_for!(LifecycleSchemaBundle))?;
    write_json(&schemas.join("jdp-request.schema.json"), &request_schema)?;
    write_json(&schemas.join("jdp-response.schema.json"), &response_schema)?;
    write_json(
        &schemas.join("revision-snapshot.schema.json"),
        &revision_schema,
    )?;
    write_json(&schemas.join("lifecycle.schema.json"), &lifecycle_schema)?;
    write_json(
        &output.join("tool-catalog.json"),
        &serde_json::to_value(tool_catalog())?,
    )?;
    Ok(())
}

fn write_json(path: &Path, value: &Value) -> Result<(), CodegenError> {
    let mut bytes = serde_json::to_vec_pretty(value)?;
    bytes.push(b'\n');
    write_stable(path, &bytes)
}

fn write_stable(path: &Path, bytes: &[u8]) -> Result<(), CodegenError> {
    let temporary = path.with_extension("tmp");
    let mut file = fs::File::create(&temporary)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    fs::rename(temporary, path)?;
    Ok(())
}

/// Binding generation failure.
#[derive(Debug, thiserror::Error)]
pub enum CodegenError {
    #[error("binding I/O failed: {0}")]
    Io(#[from] std::io::Error),
    #[error("binding serialization failed: {0}")]
    Json(#[from] serde_json::Error),
}

