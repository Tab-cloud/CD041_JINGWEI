//! Reproducible JSON Schema, tool catalog, and TypeScript binding generation.

use std::{fs, io::Write, path::Path};

use schemars::schema_for;
use serde_json::Value;

use crate::{JdpRequest, JdpResponse, tool_catalog};

/// Generates all checked-in TypeScript binding artifacts below `output`.
pub fn generate_bindings(output: &Path) -> Result<(), CodegenError> {
    let source = output.join("src");
    let schemas = output.join("schemas");
    fs::create_dir_all(&source)?;
    fs::create_dir_all(&schemas)?;

    write_stable(
        &output.join("package.json"),
        br#"{
  "name": "@jingwei/jdp-bindings",
  "version": "0.1.0",
  "private": true,
  "type": "module",
  "types": "src/generated.ts",
  "scripts": {
    "typecheck": "tsc --noEmit"
  },
  "devDependencies": {
    "typescript": "^5.9.2"
  }
}
"#,
    )?;
    write_stable(
        &output.join("tsconfig.json"),
        br#"{
  "compilerOptions": {
    "strict": true,
    "noEmit": true,
    "target": "ES2022",
    "module": "NodeNext",
    "moduleResolution": "NodeNext",
    "skipLibCheck": true
  },
  "include": ["src/**/*.ts", "test/**/*.ts"]
}
"#,
    )?;
    write_stable(
        &output.join("README.md"),
        b"# Generated JDP TypeScript binding\n\nDo not edit `src/generated.ts` or schemas by hand. Regenerate with:\n\n```text\ncargo run -p jingwei-jdp --bin jingwei-codegen -- bindings/typescript\n```\n",
    )?;
    write_stable(&source.join("generated.ts"), TYPESCRIPT.as_bytes())?;

    let request_schema = serde_json::to_value(schema_for!(JdpRequest<Value>))?;
    let response_schema = serde_json::to_value(schema_for!(JdpResponse<Value>))?;
    write_json(&schemas.join("jdp-request.schema.json"), &request_schema)?;
    write_json(&schemas.join("jdp-response.schema.json"), &response_schema)?;
    write_json(
        &output.join("tool-catalog.json"),
        &serde_json::to_value(tool_catalog())?,
    )?;
    Ok(())
}

fn write_json(path: &Path, value: &Value) -> Result<(), CodegenError> {
    let mut bytes = serde_json::to_vec_pretty(value)?;
    bytes.push(b'\n');
    write_stable(path, &bytes)
}

fn write_stable(path: &Path, bytes: &[u8]) -> Result<(), CodegenError> {
    let temporary = path.with_extension("tmp");
    let mut file = fs::File::create(&temporary)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    fs::rename(temporary, path)?;
    Ok(())
}

/// Binding generation failure.
#[derive(Debug, thiserror::Error)]
pub enum CodegenError {
    #[error("binding I/O failed: {0}")]
    Io(#[from] std::io::Error),
    #[error("binding serialization failed: {0}")]
    Json(#[from] serde_json::Error),
}

const TYPESCRIPT: &str = r#"// @generated by jingwei-codegen. DO NOT EDIT.
export const JDP_PROTOCOL_VERSION = "0.1" as const;
export const JIR_SCHEMA_VERSION = "0.1" as const;

export type OpaqueId = string;
export interface JdpRequest<T> {
  protocolVersion: typeof JDP_PROTOCOL_VERSION;
  requestId: OpaqueId;
  idempotencyKey: OpaqueId;
  workspaceId: OpaqueId;
  projectId: OpaqueId;
  operation: string;
  baseRevision?: OpaqueId;
  deadlineMs?: number;
  dryRun: boolean;
  input: T;
}
export interface FindingSummary { errors: number; warnings: number; info: number }
export interface JdpSuccess<T> {
  success: true;
  requestId: OpaqueId;
  executionId: OpaqueId;
  baseRevision?: OpaqueId;
  newRevision?: OpaqueId;
  data: T;
  artifactRefs: string[];
  evidenceRefs: string[];
  findings: FindingSummary;
}
export interface JdpFailure {
  success: false;
  requestId: OpaqueId;
  executionId?: OpaqueId;
  error: {
    code: string;
    stage: string;
    summary: string;
    fingerprint: string;
    retryable: boolean;
    objectRefs: string[];
    evidenceRefs: string[];
    suggestedActions: Array<{
      kind: "change-input" | "use-alternative" | "request-user" | "repair" | "abort-release";
      description: string;
    }>;
  };
}
export type JdpResponse<T> = JdpSuccess<T> | JdpFailure;
export interface Quantity { value: number; unit: string; dimension: string }
export interface CanonicalValue { [key: string]: unknown }
export interface JirEntity {
  id: OpaqueId; kind: string; schemaVersion: string; properties: unknown;
  provenance: { sourceKind: string; evidenceRefs: string[]; generator?: string; generatorVersion?: string };
  editControl: { policy: "ai-editable" | "ask-before-change" | "locked"; lastModifiedBy?: string };
}
export interface JirEdge { id: OpaqueId; kind: string; from: OpaqueId; to: OpaqueId; properties: unknown }
export interface DurableEvent<T> {
  schemaVersion: "0.1"; aggregateId: string; sequence: number; timestamp: string;
  sessionId?: OpaqueId; taskId?: OpaqueId; traceId?: string; type: string; data: T;
}
export interface ViewRequest {
  revision: OpaqueId; viewport: { min: Point; max: Point }; layers: string[];
  levelOfDetail: number; selection: OpaqueId[];
}
export interface Point { x: number; y: number }
export interface SemanticEditCommand { kind: string; payload: unknown }
export interface EditCommandGroup {
  editSessionId: OpaqueId; baseDraftRevision: OpaqueId; commands: SemanticEditCommand[];
  expectedPostconditions: string[]; previewHash?: string;
}
"#;
